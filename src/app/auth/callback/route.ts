import type { EmailOtpType } from "@supabase/supabase-js";
import { NextResponse, type NextRequest } from "next/server";
import { safeNextPath } from "@/lib/auth/validation";
import { createServerClient } from "@/lib/supabase/server";

/** Email links (confirm sign-up, reset password) land here and become a session. */
export async function GET(request: NextRequest) {
  const { searchParams, origin } = request.nextUrl;
  const next = safeNextPath(searchParams.get("next"));
  const code = searchParams.get("code");
  const tokenHash = searchParams.get("token_hash");
  const type = searchParams.get("type") as EmailOtpType | null;

  const supabase = await createServerClient();
  let ok = false;
  if (code) {
    ok = !(await supabase.auth.exchangeCodeForSession(code)).error;
  } else if (tokenHash && type) {
    ok = !(await supabase.auth.verifyOtp({ type, token_hash: tokenHash })).error;
  }
  // Opened on another device the code cannot be exchanged, but the email is
  // already confirmed by then, so point the user at the login form.
  return NextResponse.redirect(new URL(ok ? next : "/login?notice=confirm-failed", origin));
}
